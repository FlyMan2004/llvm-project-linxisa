#ifndef LLVM_LIB_TARGET_LINXISA_LINXISASUBTARGET_H
#define LLVM_LIB_TARGET_LINXISA_LINXISASUBTARGET_H

#include "LinxISAFrameLowering.h"
#include "LinxISAISelLowering.h"
#include "LinxISAInstrInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <memory>

#define GET_SUBTARGETINFO_HEADER
#include "LinxISAGenSubtargetInfo.inc"

namespace llvm {

class StringRef;
class TargetMachine;

class LinxISASubtarget : public LinxISAGenSubtargetInfo {
  std::unique_ptr<LinxISAInstrInfo> InstrInfo;
  std::unique_ptr<LinxISAFrameLowering> FrameLowering;
  std::unique_ptr<LinxISATargetLowering> TLInfo;
  SelectionDAGTargetInfo TSInfo;

public:
  LinxISASubtarget(const Triple &TT, StringRef CPU, StringRef FS,
                   const TargetMachine &TM);

  // Parses features string setting specified subtarget options. The definition
  // of this function is auto-generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const LinxISAInstrInfo *getInstrInfo() const override;
  const LinxISARegisterInfo *getRegisterInfo() const override;
  const LinxISAFrameLowering *getFrameLowering() const override;
  const LinxISATargetLowering *getTargetLowering() const override;
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_LINXISA_LINXISASUBTARGET_H
